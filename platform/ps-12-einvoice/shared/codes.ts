const COUNTRIES = new Set(COUNTRY_CODES);
const CURRENCIES = new Set(CURRENCY_CODES);

export function isCountryCode(value: unknown): boolean {
  return typeof value === 'string' && COUNTRIES.has(value.trim().toUpperCase());
}

export function isCurrencyCode(value: unknown): boolean {
  return typeof value === 'string' && CURRENCIES.has(value.trim().toUpperCase());
}

/** "YYYY-MM-DD", and a real day — 2026-02-30 is neither. */
export function isCalendarDate(value: unknown): boolean {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const [y, m, d] = value.split('-').map(Number) as [number, number, number];
  const date = new Date(Date.UTC(y, m - 1, d));
  return date.getUTCFullYear() === y && date.getUTCMonth() === m - 1 && date.getUTCDate() === d;
}
